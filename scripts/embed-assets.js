import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const DIST_DIR = path.join(ROOT_DIR, 'dist');
const OUTPUT_FILE = path.join(ROOT_DIR, 'src', 'server', 'embeddedAssets.ts');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2'
};

function getAllFiles(dir, base = '') {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const list = fs.readdirSync(dir);
  for (const item of list) {
    const fullPath = path.join(dir, item);
    const relPath = base ? `${base}/${item}` : item;
    // Skip unused chat screenshot attachments in assets/aistudio
    if (relPath === 'assets/aistudio' || relPath.startsWith('assets/aistudio/')) {
      continue;
    }
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(getAllFiles(fullPath, relPath));
    } else {
      results.push({ fullPath, relPath });
    }
  }
  return results;
}

const files = getAllFiles(DIST_DIR);
console.log(`Embedding ${files.length} dist assets (gzip compressed) into ${OUTPUT_FILE}...`);

let code = `// Automatically generated by scripts/embed-assets.js - DO NOT EDIT MANUALLY\n`;
code += `export interface EmbeddedAsset {\n  contentType: string;\n  encoding: 'utf-8' | 'base64' | 'gzip-base64';\n  content: string;\n}\n\n`;
code += `export const EMBEDDED_FILES: Record<string, EmbeddedAsset> = {\n`;

for (const f of files) {
  const ext = path.extname(f.fullPath).toLowerCase();
  const contentType = MIME_TYPES[ext] || 'application/octet-stream';
  const rawBuf = fs.readFileSync(f.fullPath);
  const gzBase64 = zlib.gzipSync(rawBuf, { level: 9 }).toString('base64');

  code += `  ${JSON.stringify(f.relPath)}: {\n    contentType: ${JSON.stringify(contentType)},\n    encoding: 'gzip-base64',\n    content: ${JSON.stringify(gzBase64)}\n  },\n`;
}

code += `};\n`;

fs.writeFileSync(OUTPUT_FILE, code, 'utf-8');
console.log(`[✓] Embedded assets created successfully (${(fs.statSync(OUTPUT_FILE).size / 1024).toFixed(1)} KB)`);
